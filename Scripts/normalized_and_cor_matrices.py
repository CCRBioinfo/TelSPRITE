def write_matrix(matrix, out_path):
    # Writes a 2-dimensional numpy array as a tab-delimited text file
    output = matrix.tolist()
    output = ['\t'.join([str(x) for x in row]) for row in output]
    output = '\n'.join(output)
    with open(out_path, "x") as out_file:
        out_file.write(output)

